"""Write src/data/archive_links.ts: archive lectures linked from the map, with titles and lengths read from the archive catalog.

Run from the repo root: py scripts/build_archive_links.py (needs node). Fails if an id is missing from the catalog."""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path('.')
catalog = json.loads(subprocess.check_output(
    ['node', '-e', "global.window={};require('./public/archive/catalog.js');process.stdout.write(JSON.stringify(window.LECTURES))"],
    text=True, encoding='utf-8'))
by_id = {v['id']: v for v in catalog}

# NAPLeS topic page -> lectures (same pairs as the archive's "Hear from the researchers" links)
TOPIC = {
    'cognitive-apprenticeship': ['cognitive-apprenticeship'], 'epistemic-cognition': ['epistemic-cognition'],
    'representational-learning': ['multiple-representations'], 'complexity-and-the-learning-sciences': ['complex-systems'],
    'neurocognitive-foundations-learning-sciences': ['neuromyths'], 'cognitive-tutors': ['intelligent-tutoring'],
    'multilevel-analysis': ['multilevel-basic'], 'quantitative-ethnography': ['ena-basic'],
    'analysis-of-discourse-data': ['coding-collaboration'], 'design-based-implementation-research': ['dbir'],
    'embodiment-and-embodied-design': ['embodied-cognition'], 'distributed-scaffolding': ['scaffolding-zpd'],
    'situative-cognition': ['situated-learning', 'cscl-cognitive-vs-situative'],
    'learning-progressions-in-science-education': ['learning-progressions'], 'learning-through-problem-solving': ['productive-failure'],
    'information-problem-solving': ['multiple-sources'], 'example-based-learning': ['cognitive-load'],
    'collaboration-scripts-for-cscl': ['cscl-scripts-guidance-or-straitjacket', 'cscl-can-you-script-people-to-build-on-each-other'],
    'group-awareness-tools': ['cscl-group-awareness-mirror-or-nudge'], 'knowledge-building': ['cscl-evidence-for-knowledge-building'],
    'shared-regulation-cscl': ['cscl-can-you-see-a-group-regulate-itself'], 'group-cognition': ['cscl-who-learns-when-a-group-learns'],
    'design-design-based-research': ['NdaVj7XmiEU', 'cscl-design-based-research-answer-to-what'],
    'classroom-orchestration': ['cscl-smart-dashboards-or-modest-tools'], 'automated-collaborative-process-analysis': ['edm-learning-analytics'],
}
# coded research approach (venue_methodology.json labels) -> lectures on doing that kind of study
METHOD = {
    'Experimental': ['learning-experiments', 's0HYoN8dfIM', 'multilevel-basic'],
    'Qualitative': ['video-research', 'coding-collaboration', 'multivocal-analysis'],
    'Design & Dev': ['NdaVj7XmiEU', 'dbir', 'design-cases'],
    'Data & AI': ['edm-learning-analytics', 'knowledge-tracing-bkt-dkt', 'ena-basic'],
    'Review & Meta': ['es-01-review-families', 'es-08-six-ways-to-synthesize', '9gPGEZsnIPg'],
    'Theory': ['theory-model-framework', 'cscl-cognitive-vs-situative'],
}
TECH = {
    'AI and intelligent systems': ['intelligent-tutoring', 'pedagogical-agents'],
    'VR and AR': ['Navj1yDN5-Q'],
    'Games and play': ['stealth-assessment', 'LKY8wo6KoDw'],
    'Collaborative learning': ['cscl-cooperation-or-collaboration', 'cscl-scripts-guidance-or-straitjacket'],
    'Analytics and dashboards': ['edm-learning-analytics', 'cscl-smart-dashboards-or-modest-tools'],
}
used = sorted({i for d in (TOPIC, METHOD, TECH) for ids in d.values() for i in ids})
missing = [i for i in used if i not in by_id]
assert not missing, missing
topics = {t['id'] for t in json.loads(Path('src/data/isls-topics.json').read_text(encoding='utf-8'))}
assert set(TOPIC) <= topics, set(TOPIC) - topics

lect = {i: {'title': by_id[i]['shortTitle'], 'duration': by_id[i]['duration']} for i in used}
ts = f'''// Archive lectures linked from the map (public/archive). Generated by scripts/build_archive_links.py from
// public/archive/catalog.js on the date below; every id was checked against the catalog.
export const ARCHIVE_LINKS_CHECKED = '{__import__("datetime").date.today().isoformat()}';
export interface ArchiveLecture {{ title: string; duration: string }}
export const ARCHIVE_LECTURES: Record<string, ArchiveLecture> = {json.dumps(lect, ensure_ascii=False, indent=4)};
// NAPLeS topic id (src/data/isls-topics.json) -> lectures
export const LECTURES_BY_TOPIC: Record<string, string[]> = {json.dumps(TOPIC, indent=4)};
// coded primary research approach -> lectures about that kind of study
export const LECTURES_BY_METHOD: Record<string, string[]> = {json.dumps(METHOD, indent=4)};
// coded technology area -> lectures
export const LECTURES_BY_TECH: Record<string, string[]> = {json.dumps(TECH, indent=4)};
export const lectureUrl = (id: string): string => `/archive/#lecture/${{encodeURIComponent(id)}}`;
'''
Path('src/data/archive_links.ts').write_text(ts, encoding='utf-8', newline='\n')
print('lectures', len(lect), 'topics', len(TOPIC))
